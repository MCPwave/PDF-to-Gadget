"""
@snap_engineer — Snap DevOps Agent
Generates gadget.yaml and snapcraft.yaml for Ubuntu Core Gadget Snap.
"""
import re

def _safe_str(value, default: str = "") -> str:
    return value if isinstance(value, str) else default


_ARCH_MAP = {
    "arm64": {"snap_arch": "arm64", "cross_pkg": "libc6-dev-arm64-cross", "gcc": "gcc-aarch64-linux-gnu"},
    "armhf": {"snap_arch": "armhf", "cross_pkg": "libc6-dev-armhf-cross",  "gcc": "gcc-arm-linux-gnueabihf"},
    "arm":   {"snap_arch": "armhf", "cross_pkg": "libc6-dev-armhf-cross",  "gcc": "gcc-arm-linux-gnueabihf"},
    "amd64": {"snap_arch": "amd64", "cross_pkg": "libc6-dev",              "gcc": "gcc"},
    "x86_64":{"snap_arch": "amd64", "cross_pkg": "libc6-dev",              "gcc": "gcc"},
}

_INTERFACE_MAP = {
    "i2c":      ("i2c", "i2c-{bus}"),
    "spi":      ("spi", "spi-{bus}"),
    "uart":     ("serial-port", "serial-{bus}"),
    "gpio":     ("gpio", "gpio-{bus}"),
    "pwm":      ("pwm", "pwm-{bus}"),
    "usb":      ("raw-usb", "usb-{bus}"),
    "ethernet": ("network", "ethernet-{bus}"),
    "can":      ("can-bus", "can-{bus}"),
    "camera":   ("camera", "camera-{bus}"),
    "hdmi":     ("display-control", "hdmi-{bus}"),
    "other":    ("hardware-observe", "{bus}"),
}

def _gadget_yaml(hw_map: dict, selected: list[dict]) -> str:
    board_name = _safe_str(hw_map.get("board_name"), "Custom")
    soc  = _safe_str(hw_map.get("soc"), "custom-board")
    arch = _safe_str(hw_map.get("arch"), "arm64")
    a    = _ARCH_MAP.get(arch, _ARCH_MAP["arm64"])

    slots_lines = []
    for p in selected:
        ptype  = _safe_str(p.get("type"), "other")
        iface, label_tmpl = _INTERFACE_MAP.get(ptype, _INTERFACE_MAP["other"])
        bus_or_id = _safe_str(p.get("bus")) or _safe_str(p.get("id"), "node")
        label  = label_tmpl.format(bus=bus_or_id.lower())
        desc = _safe_str(p.get("description")) or _safe_str(p.get("name"), "unnamed")
        slots_lines.append(
            f"  {label}:\n    interface: {iface}\n    # {desc}"
        )

    slots_block = "\n".join(slots_lines) if slots_lines else "  # no hardware slots defined"

    return f"""# gadget.yaml — generated by @snap_engineer
# Board: {board_name}  SoC: {soc}  Arch: {a['snap_arch']}

volumes:
  pc:
    bootloader: grub        # replace with u-boot for embedded targets
    structure:
      - name: ubuntu-seed
        role: system-seed
        filesystem: vfat
        type: EF,C12A7328-F81F-11D2-BA4B-00A0C93EC93B
        size: 1200M
      - name: ubuntu-boot
        role: system-boot
        filesystem: ext4
        type: 83,0FC63DAF-8483-4772-8E79-3D69D8477DE4
        size: 750M
      - name: ubuntu-save
        role: system-save
        filesystem: ext4
        type: 83,0FC63DAF-8483-4772-8E79-3D69D8477DE4
        size: 16M
      - name: ubuntu-data
        role: system-data
        filesystem: ext4
        type: 83,0FC63DAF-8483-4772-8E79-3D69D8477DE4
        size: 2G

slots:
{slots_block}
"""


def _snapcraft_yaml(hw_map: dict, selected: list[dict]) -> str:
    board_name = _safe_str(hw_map.get("board_name"), "Custom")
    soc  = _safe_str(hw_map.get("soc"), "custom-board")
    arch = _safe_str(hw_map.get("arch"), "arm64")
    a    = _ARCH_MAP.get(arch, _ARCH_MAP["arm64"])
    slug = re.sub(r"[^a-z0-9]+", "-", board_name.lower()).strip("-")

    slots_section = "\n".join(
        f"  {_INTERFACE_MAP.get(_safe_str(p.get('type'), 'other'), _INTERFACE_MAP['other'])[1].format(bus=(_safe_str(p.get('bus')) or _safe_str(p.get('id'), 'node')).lower())}:"
        for p in selected
    )

    return f"""# snapcraft.yaml — generated by @snap_engineer
name: {slug}-gadget
summary: Gadget snap for {board_name}
description: |
  Auto-generated Ubuntu Core gadget snap for {board_name}.
  SoC: {soc} · Arch: {a['snap_arch']}
  Includes hardware interfaces for selected peripherals.
version: "1.0"
type: gadget
base: core24

architectures:
  - build-on: amd64
    build-for: {a['snap_arch']}

build-packages:
  - {a['cross_pkg']}
  - {a['gcc']}
  - device-tree-compiler

parts:
  gadget-files:
    plugin: nil
    source: meta/
    prime:
      - gadget.yaml

  device-tree:
    plugin: dump
    source: src/
    organize:
      "*.dtb": "boot/"
    prime:
      - "boot/*.dtb"

slots:
{slots_section if slots_section else "  # no slots defined"}
"""


# ── Block diagram constants ────────────────────────────────────────────────────

_COLS    = 8   # grid width — even number, SoC sits in the exact centre
_SOC_W   = 4   # SoC block width (must be even so flanks are equal)
_SIDE_W  = (_COLS - _SOC_W) // 2   # = 2 cols on each side of SoC

# Block column-span per peripheral type (reflects HW complexity / bandwidth)
_TYPE_WIDTH = {
    # ── high-bandwidth / complex pipelines → 3 cols ─────────────────────────
    "ethernet":    3,   # MAC + PHY + DMA engine
    "usb":         3,   # host controller, hub logic
    "hdmi":        3,   # display pipeline, HDCP, audio
    "displayport": 3,   # DP TX controller
    "camera":      3,   # MIPI CSI-2 lanes + ISP
    "mipi_csi":    3,
    "mipi_dsi":    3,
    "pcie":        3,   # root complex + lanes
    # ── medium controllers → 2 cols ─────────────────────────────────────────
    "sata":   2,
    "emmc":   2,
    "sd":     2,
    "sdio":   2,
    "spi":    2,   # DMA + multiple CS lines
    "qspi":   2,
    "can":    2,   # protocol controller + filtering
    "can_fd": 2,
    "i2c":    2,   # multi-device bus + addressing
    "uart":   2,   # duplex serial + flow control
    "usart":  2,
    "i2s":    2,
    "sai":    2,
    "audio":  2,
    "adc":    2,
    "dac":    2,
    "lvds":   2,
    "other":  2,
    # ── simple / single-signal → 1 col ──────────────────────────────────────
    "gpio":     1,
    "pwm":      1,
    "rtc":      1,
    "jtag":     1,
    "swd":      1,
    "watchdog": 1,
}

