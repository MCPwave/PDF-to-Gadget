def _pack_blocks(items: list[tuple[str, int]], cols: int) -> list[str]:
    """
    Pack (mermaid_token, width) pairs into rows that sum to `cols`.
    Pads incomplete rows with `space:N`.
    Returns list of row strings (without leading indent).
    """
    rows: list[str] = []
    row_tokens: list[str] = []
    row_sum = 0

    for token, w in items:
        if row_sum + w > cols:
            pad = cols - row_sum
            if pad:
                row_tokens.append(f"space:{pad}")
            rows.append(" ".join(row_tokens))
            row_tokens, row_sum = [], 0
        row_tokens.append(token)
        row_sum += w

    if row_tokens:
        pad = cols - row_sum
        if pad:
            row_tokens.append(f"space:{pad}")
        rows.append(" ".join(row_tokens))

    return rows


def _safe_id(raw: str) -> str:
    return re.sub(r"\W+", "_", raw).strip("_") or "node"


def _mermaid_diagram(hw_map: dict, selected: list[dict]) -> str:
    """
    Hub-and-spoke block-beta layout:

      ┌─────────────────────────── Board (full width) ─────────────────────────┐
      │  [big peripheral w=3]  [big peripheral w=3]  [space…]                  │  ← top rows
      │  [left flank w=SIDE]   [    SoC  w=SOC_W  ]  [right flank w=SIDE]     │  ← centre row
      │  [medium/small remaining, packed]                                       │  ← bottom rows
      │  [power rail] [power rail] …                                            │
      └────────────────────────────────────────────────────────────────────────┘

    SoC is the biggest block, centred; large peripherals go on top; small
    peripherals flank the SoC left/right; the rest fill rows below.
    """
    board_name = _safe_str(hw_map.get("board_name"), "Custom")
    soc        = _safe_str(hw_map.get("soc"), "Unknown SoC")
    arch       = _safe_str(hw_map.get("arch"), "arm64")
    cpu_core   = _safe_str(hw_map.get("cpu_core"), "")
    rails      = hw_map.get("power_rails") or []

    # ── Build per-peripheral metadata ─────────────────────────────────────────
    all_meta: list[dict] = []
    for p in selected:
        ptype = _safe_str(p.get("type"), "other")
        w     = _TYPE_WIDTH.get(ptype, 2)
        pid   = _safe_str(p.get("id"), f"node_{len(all_meta)}")
        nid   = _safe_id(pid)
        bus   = _safe_str(p.get("bus")) or pid
        addr  = _safe_str(p.get("address"), "")
        volt  = _safe_str(p.get("voltage"), "")
        pname = _safe_str(p.get("name"), pid)
        label = pname + f"\\n{bus}" + (f" @ {addr}" if addr else "")
        if volt:
            label += f"\\n{volt}"
        token = f'{nid}["{label}"]:{w}'
        all_meta.append({"id": nid, "ptype": ptype, "w": w, "token": token})

    # Sort ascending by width so smallest go to flanks first
    all_meta.sort(key=lambda m: m["w"])

    # ── Assign peripherals to layout zones ────────────────────────────────────
    # "big" (w >= 3) → top rows above SoC, largest-first
    big_meta  = sorted([m for m in all_meta if m["w"] >= 3], key=lambda m: -m["w"])
    rest_meta = [m for m in all_meta if m["w"] < 3]   # smallest first

    # Fill left/right flanks of the SoC row (each flank = _SIDE_W cols)
    left_flank:  list[dict] = []
    right_flank: list[dict] = []
    left_sum = 0
    right_sum = 0
    below_meta: list[dict] = []

    for m in rest_meta:
        if left_sum + m["w"] <= _SIDE_W:
            left_flank.append(m)
            left_sum += m["w"]
        elif right_sum + m["w"] <= _SIDE_W:
            right_flank.append(m)
            right_sum += m["w"]
        else:
            below_meta.append(m)

    # ── Assemble diagram lines ─────────────────────────────────────────────────
    lines: list[str] = ["block-beta", f"  columns {_COLS}"]

    # Board — spans full width
    lines.append(f'  Board["{board_name}"]:{_COLS}')

    # Top rows: large peripherals packed left-to-right
    if big_meta:
        big_tokens = [(m["token"], m["w"]) for m in big_meta]
        for row in _pack_blocks(big_tokens, _COLS):
            lines.append(f"  {row}")

    # Centre row: [left flank] SoC [right flank]
    soc_label = soc + (f"\\n{cpu_core} · {arch}" if cpu_core else f"\\n{arch}")

    def _flank_str(flank: list[dict], total: int) -> str:
        parts = [m["token"] for m in flank]
        pad   = total - sum(m["w"] for m in flank)
        if pad > 0:
            parts.append(f"space:{pad}")
        return " ".join(parts)

    left_str  = _flank_str(left_flank,  _SIDE_W)
    right_str = _flank_str(right_flank, _SIDE_W)
    soc_token = f'SoC["{soc_label}"]:{_SOC_W}'
    lines.append(f"  {left_str} {soc_token} {right_str}")

    # Bottom rows: remaining medium/small peripherals
    if below_meta:
        below_tokens = [(m["token"], m["w"]) for m in below_meta]
        for row in _pack_blocks(below_tokens, _COLS):
            lines.append(f"  {row}")

    # Power rails — rounded shape, width 2
    rail_meta: list[str] = []
    if rails:
        rail_tokens: list[tuple[str, int]] = []
        for r in rails:
            rname = _safe_str(r.get("name"), "vcc")
            rn    = _safe_id(rname)
            v     = _safe_str(r.get("voltage"), "?")
            label = f"{rname}\\n{v}"
            rail_tokens.append((f'{rn}("{label}"):2', 2))
            rail_meta.append(rn)
        for row in _pack_blocks(rail_tokens, _COLS):
            lines.append(f"  {row}")

    # ── Arrows ────────────────────────────────────────────────────────────────
    lines.append("")
    lines.append("  Board --> SoC")
    for m in all_meta:
        lines.append(f"  SoC --> {m['id']}")

    selected_ids = {_safe_str(p.get("id")) for p in selected if _safe_str(p.get("id"))}
    for r in rails:
        rn = _safe_id(_safe_str(r.get("name"), "vcc"))
        for sid in r.get("supplies", []):
            sid_s = _safe_str(sid)
            if sid_s in selected_ids:
                lines.append(f"  {rn} --> {_safe_id(sid_s)}")

    # ── Styles ────────────────────────────────────────────────────────────────
    lines.append("")
    lines.append("  style Board fill:#1a1a2e,stroke:#e0e0ff,color:#e0e0ff,stroke-width:2px")
    lines.append(f"  style SoC fill:#b35c00,stroke:#ff9900,color:#fff,stroke-width:3px")
    for m in all_meta:
        s = _TYPE_STYLE.get(m["ptype"], _TYPE_STYLE["other"])
        lines.append(f"  style {m['id']} {s}")
    for rn in rail_meta:
        lines.append(f"  style {rn} fill:#002244,stroke:#0066cc,color:#cce4ff")

    return "\n".join(lines)


# ── Public API ──────────────────────────────────────────────────────────────────

def run(hw_map: dict, selected_ids: list[str]) -> dict:
    selected = [p for p in hw_map.get("peripherals", []) if _safe_str(p.get("id")) in selected_ids]

    return {
        "gadget_yaml":    _gadget_yaml(hw_map, selected),
        "snapcraft_yaml": _snapcraft_yaml(hw_map, selected),
        "mermaid":        _mermaid_diagram(hw_map, selected),
    }
